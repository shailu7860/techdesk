// Regenerates customHttp.yml from scripts/security-headers.mjs. Run: node scripts/write-custom-http.mjs
import { writeFileSync } from "node:fs";
import { cacheRules, securityHeaders } from "./security-headers.mjs";

const q = (s) => `'${s.replace(/'/g, "''")}'`;
let y = "# Generated by scripts/write-custom-http.mjs; edit scripts/security-headers.mjs instead.\n";
y += "# The Content-Security-Policy is injected per page at build time (scripts/csp.mjs).\ncustomHeaders:\n";
y += "  - pattern: '**/*'\n    headers:\n";
for (const [k, v] of Object.entries(securityHeaders)) y += `      - key: ${q(k)}\n        value: ${q(v)}\n`;
for (const r of cacheRules)
  y += `  - pattern: ${q(r.pattern)}\n    headers:\n      - key: 'Cache-Control'\n        value: ${q(r.value)}\n`;
writeFileSync(new URL("../customHttp.yml", import.meta.url), y);
console.log("customHttp.yml written");
